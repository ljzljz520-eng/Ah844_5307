func RouteByCode(code string) (RouteCode, bool) {
	for _, r := range RouteCatalog {
		if r.Code == code {
			return r, true
		}
	}
	return RouteCode{}, false
}
func RoutesInRegion(region string) []RouteCode {
	out := []RouteCode{}
	for _, r := range RouteCatalog {
		if r.Region == region {
			out = append(out, r)
		}
	}
	return out
}
func CatalogDistance(code string) int {
	if r, ok := RouteByCode(code); ok {
		return r.Distance
	}
	return 0
}
